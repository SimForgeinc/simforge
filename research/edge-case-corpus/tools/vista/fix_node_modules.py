"""Make the worktree's node_modules resolve @simforge/* to THE WORKTREE.

Every packages/*/node_modules and the root node_modules in this worktree is a symlink into the MAIN
checkout, so `node packages/cli/bin/simforge.js` loaded cli/src from here and every OTHER
workspace package from main. Any end-to-end CLI proof therefore exercised main's engine, materializer
and schema, not ours.

Fix: replace each symlinked node_modules with a REAL directory that re-links every third-party entry
back to main's copy (so nothing is downloaded or duplicated) and points @simforge/* at this
worktree's packages. Reversible: delete the real dir and re-create the original symlink.
"""
import os, sys, json

WT = '/Users/michaelvu-simforge/Documents/Programming/SimForge-vista'
MAIN = '/Users/michaelvu-simforge/Documents/Programming/SimForge'


def wt_packages():
    root = os.path.join(WT, 'packages')
    out = {}
    for name in os.listdir(root):
        pj = os.path.join(root, name, 'package.json')
        if os.path.exists(pj):
            try:
                out[json.load(open(pj))['name']] = os.path.join(root, name)
            except Exception:                                     # noqa: BLE001
                pass
    return out


def relink(nm_path, pkgmap, report):
    if not os.path.islink(nm_path):
        return
    target = os.path.realpath(nm_path)
    if not target.startswith(MAIN):
        return
    os.unlink(nm_path)
    os.makedirs(nm_path, exist_ok=True)
    for entry in os.listdir(target):
        src, dst = os.path.join(target, entry), os.path.join(nm_path, entry)
        if entry == '@simforge':
            os.makedirs(dst, exist_ok=True)
            for sub in os.listdir(src):
                full = f'@simforge/{sub}'
                link = os.path.join(dst, sub)
                if full in pkgmap:
                    os.symlink(pkgmap[full], link)          # -> THE WORKTREE
                    report.setdefault('redirected', []).append(f'{nm_path}:{full}')
                else:
                    os.symlink(os.path.join(src, sub), link)
        else:
            os.symlink(src, dst)
    report.setdefault('rebuilt', []).append(nm_path)


if __name__ == '__main__':
    pkgmap = wt_packages()
    report = {}
    relink(os.path.join(WT, 'node_modules'), pkgmap, report)
    for name in sorted(os.listdir(os.path.join(WT, 'packages'))):
        relink(os.path.join(WT, 'packages', name, 'node_modules'), pkgmap, report)
    for name in sorted(os.listdir(os.path.join(WT, 'apps'))) if os.path.isdir(os.path.join(WT, 'apps')) else []:
        relink(os.path.join(WT, 'apps', name, 'node_modules'), pkgmap, report)
    print(f"rebuilt {len(report.get('rebuilt', []))} node_modules dirs, "
          f"redirected {len(report.get('redirected', []))} @simforge links to the worktree")
