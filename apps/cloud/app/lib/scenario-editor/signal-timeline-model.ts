/**
 * The conflict-free groups the lane paints, with shared heads fused.
 *
 * Fusing matters here and nowhere else: two movements on one physical head
 * cannot show different colours, so a surface that paints whole groups must not
 * offer to try.
 */
export function timelineGroups(
  movements: readonly JunctionMovementBinding[],
): string[][] {
  return deriveConflictFreeGroups(movements, { unionSharedHeads: true });
}

export function timelineRowId(movementIds: readonly string[]): string {
  return [...movementIds].sort().join("|");
}

/** A row header that names the movements without becoming a paragraph. */
export function timelineRowLabel(
  movements: readonly JunctionMovementBinding[],
  movementIds: readonly string[],
): string {
  const byId = new Map(movements.map((movement) => [movement.movement_id, movement]));
  const labels = movementIds.map((id) => byId.get(id)?.label ?? id);
  if (labels.length === 0) return "No movements";
  if (labels.length === 1) return labels[0]!;
  return `${labels[0]} +${labels.length - 1}`;
}

function bandSignature(bands: readonly TimelineBand[]): string {
  return bands
    .map((band) => `${band.state}@${roundSeconds(band.start_s)}-${roundSeconds(band.end_s)}`)
    .join(",");
}

/**
 * Every movement's colour over time, from the plan's program.
 *
 * `programBands` is the existing, exact, already-tested decompiler — it applies
 * the same hold-your-colour rule `movementStateAt` does, so what comes back is
 * the sequence a viewer would actually see rather than one band per interval.
 */
function bandsByMovement(
  plan: JunctionSignalPlan,
  durationSeconds: number,
  autoYellow: boolean,
): Map<string, TimelineBand[]> {
  const byMovement = new Map<string, TimelineBand[]>();
  const program = plan.program;
  if (program && program.cycle.length > 0 && durationSeconds > 0) {
    for (const band of programBands(program, plan.movements, durationSeconds)) {
      const bands = byMovement.get(band.movement_id) ?? [];
      // Rounded because `programBands` accumulates a cursor across the cycle, so
      // a boundary the author put at 29.6 comes back as 29.599999999999998 —
      // enough to make an otherwise exact round trip fail on its last band.
      bands.push({
        state: band.state,
        start_s: roundSeconds(band.start_s),
        end_s: roundSeconds(band.end_s),
      });
      byMovement.set(band.movement_id, bands);
    }
  }
  for (const movement of plan.movements) {
    // A movement the cycle never names has no authored colour. Forced green is
    // the scenario-wide default (plan §11), so that is what it is showing, and
    // saying so here makes the next compile state it explicitly.
    if (!byMovement.has(movement.movement_id)) {
      byMovement.set(movement.movement_id, [
        { state: "green", start_s: 0, end_s: durationSeconds },
      ]);
    }
  }
  for (const bands of byMovement.values()) {
    bands.sort((left, right) => left.start_s - right.start_s);
    if (autoYellow) markDerivedYellows(bands);
  }
  return byMovement;
}

/**
 * Mark the yellows the compiler would have produced anyway.
 *
 * Exactly {@link SIGNAL_AUTO_YELLOW_S} long, immediately after a green and
 * immediately before a red. Nothing else qualifies, so a 2 s yellow an author
 * drew by hand stays theirs.
 */
function markDerivedYellows(bands: TimelineBand[]): void {
  for (const [index, band] of bands.entries()) {
    const previous = bands[index - 1];
    const next = bands[index + 1];
    if (
      band.state === "yellow" &&
      previous?.state === "green" &&
      next?.state === "red" &&
      Math.abs(band.end_s - band.start_s - SIGNAL_AUTO_YELLOW_S) < EPSILON
    ) {
      band.derived = true;
    }
  }
}

/**
 * The lane's rows for one plan.
 *
 * Conflict-free groups first (so every row is safely paintable), then split by
 * band signature (so a hand-edited program that gave two members of one group
 * different colours still shows both truthfully).
 */
export function decompileProgramToRows(
  plan: JunctionSignalPlan,
  durationSeconds: number,
  options: { autoYellow?: boolean; tier?: TimelineTier } = {},
): TimelineRow[] {
  if (durationSeconds <= 0) return [];
  const autoYellow = options.autoYellow ?? true;
  const byMovement = bandsByMovement(plan, durationSeconds, autoYellow);
  const known = new Set(plan.movements.map((movement) => movement.movement_id));
  const orphans = [...byMovement.keys()].filter((id) => !known.has(id)).sort();

  const groups =
    options.tier === "movement"
      ? [...known].sort().map((id) => [id])
      : timelineGroups(plan.movements);

  const rows: TimelineRow[] = [];
  for (const group of [...groups, ...orphans.map((id) => [id])]) {
    const bySignature = new Map<string, string[]>();
    for (const movementId of group) {
      const signature = bandSignature(byMovement.get(movementId) ?? []);
      bySignature.set(signature, [...(bySignature.get(signature) ?? []), movementId]);
    }
    for (const movementIds of bySignature.values()) {
      const sorted = [...movementIds].sort();
      rows.push({
        id: timelineRowId(sorted),
        label: timelineRowLabel(plan.movements, sorted),
        movement_ids: sorted,
        bands: (byMovement.get(sorted[0]!) ?? []).map((band) => ({ ...band })),
      });
    }
  }
  return rows;
}

