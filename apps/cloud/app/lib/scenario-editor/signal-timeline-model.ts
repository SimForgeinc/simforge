function rowsConflict(
  movements: readonly JunctionMovementBinding[],
  left: TimelineRow,
  right: TimelineRow,
): boolean {
  const conflicts = new Map(
    movements.map((movement) => [movement.movement_id, new Set(movement.conflicts_with)]),
  );
  return left.movement_ids.some((id) =>
    right.movement_ids.some((other) => conflicts.get(id)?.has(other) ?? false),
  );
}

/**
 * Paint one row and settle the junction around it.
 *
 * Every conflicting row takes the opposite colour over the same span. This is
 * the whole "I should not have to micromanage every single light" requirement:
 * one gesture leaves the junction in a state that runs. It also makes
 * `conflicting_green` unreachable from this tier, which turns that warning into
 * a precise signal that the author descended to the movement tier on purpose.
 */
export function paintRows(
  rows: readonly TimelineRow[],
  movements: readonly JunctionMovementBinding[],
  targetRowId: string,
  span: { start_s: number; end_s: number },
  state: BehaviorSignalState,
  durationSeconds: number,
): TimelineRow[] {
  const target = rows.find((row) => row.id === targetRowId);
  if (!target) return [...rows];
  const opposite = oppositeSignalState(state);
  return rows.map((row) => {
    if (row.id === targetRowId) {
      return { ...row, bands: paintBands(row.bands, span, state, durationSeconds) };
    }
    if (!rowsConflict(movements, target, row)) return row;
    return { ...row, bands: paintBands(row.bands, span, opposite, durationSeconds) };
  });
}

/**
 * Where two conflicting rows are green at the same time.
 *
 * `detectSignalPlanWarnings` already reports this per phase; the lane wants it
 * per SPAN, so the hatch lands on the seconds that are wrong instead of on a
 * list item that names a phase index the author never sees. Unreachable from the
 * junction and group tiers by construction, so anything drawn here is a precise
 * report that the author descended to the movement tier.
 */
export function conflictingGreenSpans(
  rows: readonly TimelineRow[],
  movements: readonly JunctionMovementBinding[],
): Array<{ rowId: string; start_s: number; end_s: number }> {
  const spans: Array<{ rowId: string; start_s: number; end_s: number }> = [];
  for (const row of rows) {
    for (const other of rows) {
      if (row.id === other.id || !rowsConflict(movements, row, other)) continue;
      for (const band of row.bands) {
        if (band.state !== "green") continue;
        for (const rival of other.bands) {
          if (rival.state !== "green") continue;
          const start = Math.max(band.start_s, rival.start_s);
          const end = Math.min(band.end_s, rival.end_s);
          if (end - start > EPSILON) spans.push({ rowId: row.id, start_s: start, end_s: end });
        }
      }
    }
  }
  return spans;
}

/**
 * The row an author means when they paint the collapsed junction row.
 *
 * Precedence, most specific first:
 *
 * 1. **The light they clicked.** Pointing at a physical head is the most
 *    explicit statement of intent available — the author walked up to one light
 *    and said "this one" — so it outranks everything inferred.
 * 2. **The selected actor's approach.** Select the subject, paint the junction row,
 *    and you have painted the subject's light.
 * 3. **The first group**, which is the one the synthesizer greens first.
 *
 * A reference naming several movements (one head commonly drives both the
 * through and the right) matches the row holding ANY of them: `timelineGroups`
 * fuses movements that share a head, so they are all in one row anyway.
 */
export function primaryRowId(
  rows: readonly TimelineRow[],
  reference: string | null | { referenceMovementIds?: readonly string[]; subjectMovementId?: string | null },
): string | null {
  if (rows.length === 0) return null;
  const referenceIds =
    typeof reference === "string" || reference == null
      ? []
      : (reference.referenceMovementIds ?? []);
  const subjectMovementId =
    typeof reference === "string" ? reference : (reference?.subjectMovementId ?? null);

  if (referenceIds.length > 0) {
    const owning = rows.find((row) =>
      row.movement_ids.some((id) => referenceIds.includes(id)),
    );
    if (owning) return owning.id;
  }
  if (subjectMovementId) {
    const owning = rows.find((row) => row.movement_ids.includes(subjectMovementId));
    if (owning) return owning.id;
  }
  return rows[0]!.id;
}

/**
 * Move every row's boundary that sits at `fromSeconds` (Alt+drag).
 *
 * Junctions are coordinated: the moment one approach turns green the other
 * turns red, and retiming one edge alone would break that. Rows with no
 * boundary there are untouched.
 */
export function retimeRowsAt(
  rows: readonly TimelineRow[],
  fromSeconds: number,
  toSeconds: number,
  durationSeconds: number,
): TimelineRow[] {
  return rows.map((row) => {
    const index = row.bands.findIndex(
      (band, position) =>
        position < row.bands.length - 1 &&
        Math.abs(band.end_s - fromSeconds) < TIMELINE_TIME_GRID_S / 2 + EPSILON,
    );
    if (index === -1) return row;
    return { ...row, bands: retimeBoundary(row.bands, index, toSeconds, durationSeconds) };
  });
}

