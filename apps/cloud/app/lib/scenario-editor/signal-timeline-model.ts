function normalizeDegrees(degrees: number): number {
  return ((((degrees + 180) % 360) + 360) % 360) - 180;
}

/**
 * Which movement an actor standing at `from` will meet at this junction.
 *
 * Matches the bearing the actor must travel to reach the junction against each
 * movement's approach heading, both in the CARLA basis the movement table
 * stores. Deliberately crude — it reads a straight line, not a route — so it is
 * gated hard on distance and angle and answers null rather than guess. The
 * precise answer lives in `PreviewRouteLandmark`, which is server-side only
 * today (plan §4.3, Phase 4).
 */
export function nearestApproachMovementId(
  movements: readonly JunctionMovementBinding[],
  from: { x: number; y: number } | null,
  junctionCenter: { x: number; y: number } | null,
  options: { maxDistanceM?: number; maxHeadingDeltaDeg?: number } = {},
): string | null {
  if (!from || !junctionCenter) return null;
  const maxDistance = options.maxDistanceM ?? 200;
  const maxDelta = options.maxHeadingDeltaDeg ?? 60;
  const dx = junctionCenter.x - from.x;
  const dy = junctionCenter.y - from.y;
  const distance = Math.hypot(dx, dy);
  if (distance > maxDistance || distance < EPSILON) return null;

  const bearing = (Math.atan2(dy, dx) * 180) / Math.PI;
  let best: { movementId: string; delta: number } | null = null;
  for (const movement of movements) {
    if (movement.approach_heading_deg == null) continue;
    const delta = Math.abs(normalizeDegrees(movement.approach_heading_deg - bearing));
    if (delta > maxDelta) continue;
    if (!best || delta < best.delta) best = { movementId: movement.movement_id, delta };
  }
  return best?.movementId ?? null;
}
