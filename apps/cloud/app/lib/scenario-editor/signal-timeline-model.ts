/**
 * The seed for a junction nobody has authored: green, everywhere, all scenario.
 *
 * This is not a design flourish — it is what the runtime already does. Michael's
 * 2026-07-26 decision (plan §11) forces every dynamic light green on any
 * junction with no authored plan, and the browser engine reads an unauthored
 * junction as "proceed", so an all-green full-duration program is the one seed
 * that changes NOTHING when the author opens the timeline. The synthesized
 * alternating cycle is one click away for authors who want a real intersection.
 */
export function seedForcedGreenProgram(
  movements: readonly JunctionMovementBinding[],
): SignalPhaseProgram | null {
  if (movements.length === 0) return null;
  return {
    cycle: [
      {
        duration_s: SIGNAL_HOLD_TAIL_S,
        label: "Forced green",
        states: Object.fromEntries(
          movements.map((movement) => [movement.movement_id, "green" as const]),
        ),
      },
    ],
    offset_s: 0,
  };
}

/** The alternating cycle behind "Seed cycle" — the shared synthesizer. */
export function seedCycleProgram(
  movements: readonly JunctionMovementBinding[],
): SignalPhaseProgram | null {
  return synthesizeSignalProgram(movements);
}

/**
 * Switch a plan into the timeline view.
 *
 * Writes `program` mode, because the timeline IS the program — no fourth
 * executor branch, no schema bump. Anything already authored survives: an author
 * who painted, tried Static, and came back finds their timeline intact.
 */
export function withTimelineMode(plan: JunctionSignalPlan): JunctionSignalPlan {
  const next: JunctionSignalPlan = { ...plan, mode: "program" };
  if ((next.program?.cycle.length ?? 0) === 0) {
    const seeded = seedForcedGreenProgram(plan.movements);
    if (seeded) next.program = seeded;
  }
  return next;
}

/** True when the plan is still the untouched forced-green seed. */
export function isForcedGreenSeed(plan: JunctionSignalPlan): boolean {
  const cycle = plan.program?.cycle ?? [];
  if (cycle.length !== 1) return false;
  const states = Object.values(cycle[0]!.states);
  return states.length > 0 && states.every((state) => state === "green");
}

