/**
 * Paint a span, destructively.
 *
 * Neighbours truncate at the span's edges, fully covered bands disappear, and
 * same-colour neighbours merge. This is the rule that makes drag-paint feel like
 * a paint bucket rather than an insert, and it is why overlap is never stored.
 */
export function paintBands(
  bands: readonly TimelineBand[],
  span: { start_s: number; end_s: number },
  state: BehaviorSignalState,
  durationSeconds: number,
): TimelineBand[] {
  const start = Math.max(0, snapTimelineSeconds(Math.min(span.start_s, span.end_s)));
  const end = Math.min(durationSeconds, snapTimelineSeconds(Math.max(span.start_s, span.end_s)));
  if (end - start < EPSILON) return [...bands];

  const out: TimelineBand[] = [];
  for (const band of bands) {
    // A derived yellow under the brush stops being derived the moment its
    // shape changes; the compiler will re-derive whatever the result needs.
    if (band.end_s <= start || band.start_s >= end) {
      out.push({ ...band });
      continue;
    }
    if (band.start_s < start) out.push({ ...band, end_s: start });
    if (band.end_s > end) out.push({ ...band, start_s: end });
  }
  out.push({ state, start_s: start, end_s: end });
  return normalizeBands(out, durationSeconds);
}

/** Interior boundaries — the draggable edges between bands. */
export function bandBoundaries(bands: readonly TimelineBand[]): number[] {
  return bands.slice(0, -1).map((band) => band.end_s);
}

/**
 * Move the boundary between bands `index` and `index + 1`.
 *
 * Both neighbours resize; neither may collapse past
 * {@link TIMELINE_MIN_BAND_S}. A derived yellow is not draggable — the compiler
 * owns its edges — so a retime that would move one is refused rather than
 * silently ignored downstream.
 */
export function retimeBoundary(
  bands: readonly TimelineBand[],
  index: number,
  timeSeconds: number,
  durationSeconds: number,
): TimelineBand[] {
  const left = bands[index];
  const right = bands[index + 1];
  if (!left || !right) return [...bands];
  if (left.derived || right.derived) return [...bands];
  const lowest = left.start_s + TIMELINE_MIN_BAND_S;
  const highest = right.end_s - TIMELINE_MIN_BAND_S;
  if (highest < lowest) return [...bands];
  const at = Math.min(highest, Math.max(lowest, snapTimelineSeconds(timeSeconds)));
  return normalizeBands(
    bands.map((band, position) => {
      if (position === index) return { ...band, end_s: at };
      if (position === index + 1) return { ...band, start_s: at };
      return { ...band };
    }),
    durationSeconds,
  );
}

/** Delete a boundary: the two bands merge, taking the LEFT band's colour. */
export function deleteBoundary(
  bands: readonly TimelineBand[],
  index: number,
  durationSeconds: number,
): TimelineBand[] {
  const left = bands[index];
  const right = bands[index + 1];
  if (!left || !right) return [...bands];
  const merged = bands.map((band, position) =>
    position === index + 1
      ? { state: left.state, start_s: band.start_s, end_s: band.end_s }
      : { ...band },
  );
  return normalizeBands(merged, durationSeconds);
}

/** Advance one band's colour: red → green → yellow, the panel's order. */
export function cycleBand(
  bands: readonly TimelineBand[],
  index: number,
  durationSeconds: number,
): TimelineBand[] {
  const band = bands[index];
  if (!band) return [...bands];
  return normalizeBands(
    bands.map((entry, position) =>
      position === index
        ? { state: nextSignalState(entry.state), start_s: entry.start_s, end_s: entry.end_s }
        : { ...entry },
    ),
    durationSeconds,
  );
}

