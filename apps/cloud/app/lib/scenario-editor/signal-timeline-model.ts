// Compiling
// ---------------------------------------------------------------------------

/**
 * Give a derived band's time back to the band before it.
 *
 * The compiler re-derives auto-yellow from scratch, so it must first see the
 * bands as the author drew them — a green that runs all the way to the red.
 */
export function stripDerivedBands(bands: readonly TimelineBand[]): TimelineBand[] {
  const out: TimelineBand[] = [];
  for (const band of bands) {
    if (!band.derived) {
      out.push({ state: band.state, start_s: band.start_s, end_s: band.end_s });
      continue;
    }
    const previous = out[out.length - 1];
    if (previous) previous.end_s = band.end_s;
    else out.push({ state: band.state, start_s: band.start_s, end_s: band.end_s });
  }
  return out;
}

/** Insert the yellow every green→red flip needs, ending at the boundary. */
export function withAutoYellow(bands: readonly TimelineBand[]): TimelineBand[] {
  const out: TimelineBand[] = [];
  for (const [index, band] of bands.entries()) {
    const next = bands[index + 1];
    const duration = band.end_s - band.start_s;
    if (
      band.state !== "green" ||
      next?.state !== "red" ||
      // A green shorter than the yellow would be replaced by it rather than
      // trimmed. The author asked for that green; leave the flip raw.
      duration <= SIGNAL_AUTO_YELLOW_S + EPSILON
    ) {
      out.push({ ...band });
      continue;
    }
    const boundary = band.end_s;
    out.push({ ...band, end_s: roundSeconds(boundary - SIGNAL_AUTO_YELLOW_S) });
    out.push({
      state: "yellow",
      start_s: roundSeconds(boundary - SIGNAL_AUTO_YELLOW_S),
      end_s: boundary,
      derived: true,
    });
  }
  return out;
}

function stateAt(bands: readonly TimelineBand[], t: number): BehaviorSignalState | null {
  let held: BehaviorSignalState | null = null;
  for (const band of bands) {
    if (band.start_s <= t && band.end_s > t) return band.state;
    if (band.end_s <= t) held = band.state;
  }
  return held;
}

/**
 * Bands → `SignalPhaseProgram`.
 *
 * Slices at the union of every row's boundaries and emits a FULL state map per
 * slice — every movement, every time. That is deliberate on three counts: it
 * drives the `incomplete_phase` warning count to zero, it guarantees the
 * compiler can never name a movement outside the table (one parse throw drops
 * the signal layer for the WHOLE scenario, not just this plan), and it makes the
 * round-trip exact, because nothing depends on the hold-your-colour walk.
 */
export function compileRowsToProgram(
  rows: readonly TimelineRow[],
  movements: readonly JunctionMovementBinding[],
  durationSeconds: number,
  options: { autoYellow?: boolean } = {},
): SignalPhaseProgram | null {
  if (durationSeconds <= 0) return null;
  const autoYellow = options.autoYellow ?? true;

  const byMovement = new Map<string, TimelineBand[]>();
  for (const row of rows) {
    const normalized = normalizeBands(row.bands, durationSeconds);
    const stripped = stripDerivedBands(normalized);
    const compiled = autoYellow ? withAutoYellow(stripped) : stripped;
    for (const movementId of row.movement_ids) {
      byMovement.set(movementId, compiled.map((band) => ({ ...band })));
    }
  }
  for (const movement of movements) {
    if (!byMovement.has(movement.movement_id)) {
      byMovement.set(movement.movement_id, [
        { state: "green", start_s: 0, end_s: durationSeconds },
      ]);
    }
  }
  if (byMovement.size === 0) return null;

  const edges = new Set<number>([0, durationSeconds]);
  for (const bands of byMovement.values()) {
    for (const band of bands) {
      if (band.start_s > 0 && band.start_s < durationSeconds) edges.add(roundSeconds(band.start_s));
      if (band.end_s > 0 && band.end_s < durationSeconds) edges.add(roundSeconds(band.end_s));
    }
  }
  const boundaries = [...edges].sort((left, right) => left - right);

  const cycle: SignalPhaseInterval[] = [];
  for (const [index, start] of boundaries.slice(0, -1).entries()) {
    const end = boundaries[index + 1]!;
    const duration = roundSeconds(end - start);
    if (duration <= EPSILON) continue;
    const mid = (start + end) / 2;
    const states: Record<string, BehaviorSignalState> = {};
    for (const [movementId, bands] of byMovement) {
      states[movementId] = stateAt(bands, mid) ?? "green";
    }
    const previous = cycle[cycle.length - 1];
    if (previous && sameStates(previous.states, states)) {
      previous.duration_s = roundSeconds(previous.duration_s + duration);
      continue;
    }
    cycle.push({ duration_s: duration, states });
  }
  if (cycle.length === 0) return null;

  // The tail holds instead of wrapping: a painted timeline is one-shot.
  cycle[cycle.length - 1] = {
    ...cycle[cycle.length - 1]!,
    duration_s: SIGNAL_HOLD_TAIL_S,
    label: "Holds",
  };
  return { cycle, offset_s: 0 };
}

function sameStates(
  left: Record<string, BehaviorSignalState>,
  right: Record<string, BehaviorSignalState>,
): boolean {
  const keys = Object.keys(left);
  if (keys.length !== Object.keys(right).length) return false;
  return keys.every((key) => left[key] === right[key]);
}

/**
 * Clamp to the timeline, drop slivers, close gaps.
 *
 * Painting cannot produce a gap, but a plan that arrived from somewhere else
 * can; a gap would compile to a slice whose colour came from the hold-your-
 * colour walk instead of from the lane the author is looking at.
 */
export function normalizeBands(
  bands: readonly TimelineBand[],
  durationSeconds: number,
): TimelineBand[] {
  const clipped = bands
    .map((band) => ({
      ...band,
      start_s: Math.max(0, roundSeconds(band.start_s)),
      end_s: Math.min(durationSeconds, roundSeconds(band.end_s)),
    }))
    .filter((band) => band.end_s - band.start_s > EPSILON)
    .sort((left, right) => left.start_s - right.start_s);
  if (clipped.length === 0) return [];

  const out: TimelineBand[] = [];
  for (const band of clipped) {
    const previous = out[out.length - 1];
    if (!previous) {
      // Anything before the first band holds its colour — the same rule the
      // executor applies when a cycle starts mid-phase.
      out.push({ ...band, start_s: 0 });
      continue;
    }
    if (band.start_s < previous.end_s) band.start_s = previous.end_s;
    if (band.end_s - band.start_s <= EPSILON) continue;
    if (band.start_s > previous.end_s) previous.end_s = band.start_s;
    if (previous.state === band.state && previous.derived === band.derived) {
      previous.end_s = band.end_s;
      continue;
    }
    out.push({ ...band });
  }
  out[out.length - 1]!.end_s = durationSeconds;
  return out;
}

