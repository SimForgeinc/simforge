/**
 * Interval painting for traffic signals — the pure model behind the timeline
 * lane (traffic-light timeline plan 2026-07-25, Phase 1).
 *
 * The author paints coloured spans on a time axis. That is a VIEW over the
 * existing `program` mode, not a new schema mode: `SignalPhaseInterval.states`
 * is already a per-movement colour map inside one time slice, which is exactly a
 * painted band sliced at the union of boundaries. So painting compiles bands →
 * `SignalPhaseProgram`, opening decompiles the program → bands, and neither the
 * worker, the xosc writer nor the preview engine learns anything new.
 *
 * Three properties hold this together, and the round-trip test is the gate:
 *
 * 1. **One-shot, not cyclic.** A painted timeline means "green from 4 s onward",
 *    but a program is a repeating cycle in all three runtimes. The compiler's
 *    last phase therefore holds for {@link SIGNAL_HOLD_TAIL_S} = 3600 s, which
 *    no real scenario reaches. Not `Infinity`: `0 * Infinity` is `NaN` and would
 *    poison the xosc writer's boundary unroll, and JSON round-trips it to null.
 *
 * 2. **Auto-yellow is DERIVED, never authored intent.** Compiling inserts
 *    {@link SIGNAL_AUTO_YELLOW_S} of yellow ENDING at each green→red boundary —
 *    eating the green's tail, so "red at 4" still means red at 4. Decompiling
 *    marks such a band `derived`, and compiling strips derived bands (giving the
 *    time back to the green before it) before re-deriving them. That is what
 *    makes the operation idempotent across any number of round-trips. A yellow
 *    the author hand-paints in exactly that shape simply becomes derived, which
 *    is fine: the compiled output is identical either way.
 *
 * 3. **Paint is destructive within a row.** A span replaces whatever is under
 *    it — neighbours truncate, covered bands vanish, same-colour neighbours
 *    merge. Overlap is never a stored state; it is resolved at paint time.
 *
 * Rows are DERIVED, never stored: conflict-free groups from the shared
 * `deriveConflictFreeGroups` (the same partition `detectSignalPlanWarnings`
 * checks against, so a group-tier paint cannot produce a `conflicting_green`),
 * split further by identical band signature so a hand-edited or
 * worker-round-tripped program still displays sensibly. No schema field, and no
 * way for a stored group to disagree with the plan it describes.
 */

import {
  deriveConflictFreeGroups,
  synthesizeSignalProgram,
  type BehaviorSignalState,
  type JunctionMovementBinding,
  type JunctionSignalPlan,
  type SignalPhaseInterval,
  type SignalPhaseProgram,
} from "@simcloud/shared";
import {
  nextSignalState,
  programBands,
} from "@/app/lib/scenario-editor/signals/signal-plan-model";

/** Yellow inserted at every green→red flip, ending at the boundary. */
export const SIGNAL_AUTO_YELLOW_S = 3.0;

/**
 * The final phase's duration. Long enough that no scenario reaches the wrap, so
 * a painted (one-shot) timeline never repeats; short enough to read as "one
 * hour" in the phase list and to survive a JSON round-trip.
 */
export const SIGNAL_HOLD_TAIL_S = 3600;

/** Painted edges snap here. Program boundaries have no such constraint — this
 *  is for the author's benefit (and to keep round-trips float-exact). */
export const TIMELINE_TIME_GRID_S = 0.1;

/** Below this a band is not worth keeping; paints and retimes clamp to it. */
export const TIMELINE_MIN_BAND_S = 0.2;

const EPSILON = 1e-6;

export type TimelineBand = {
  state: BehaviorSignalState;
  start_s: number;
  end_s: number;
  /** Regenerated by the compiler: hatched, and not draggable. */
  derived?: boolean;
};

/** One paintable lane row: a set of movements that move as one. */
export type TimelineRow = {
  /** Stable across re-derivations: the sorted movement ids. */
  id: string;
  label: string;
  movement_ids: string[];
  bands: TimelineBand[];
};

/** How far down the junction → group → movement disclosure the lane is open. */
export type TimelineTier = "junction" | "group" | "movement";

export function snapTimelineSeconds(seconds: number): number {
  const snapped = Math.round(seconds / TIMELINE_TIME_GRID_S) * TIMELINE_TIME_GRID_S;
  return Math.round(snapped * 1e6) / 1e6;
}

function roundSeconds(seconds: number): number {
  return Math.round(seconds * 1e6) / 1e6;
}

/**
 * The colour a conflicting group takes when this one is painted.
 *
 * Yellow maps to red rather than to green: yellow is a clearing interval, and
 * the cross traffic is not released until it is over.
 */
export function oppositeSignalState(state: BehaviorSignalState): BehaviorSignalState {
  return state === "red" ? "green" : "red";
}

